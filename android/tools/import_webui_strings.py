#!/usr/bin/env python3
"""Regenerate the app's shared string resources from upstream's WebUI translations.

Run manually after upstream changes module/webroot/i18n.js; the output is committed.
Keys keep their WebUI meaning ("a.b" becomes "a_b"); {placeholders} stay literal and
are substituted in Kotlin. App-only strings live in strings_app.xml and are untouched.
"""
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "module/webroot/i18n.js"
RES = ROOT / "android/app/src/main/res"
# Android resource qualifiers per WebUI locale. Traditional Chinese covers TW/HK/Hant.
TARGETS = {"en": ["values"], "zh-CN": ["values-zh", "values-zh-rCN"],
           "zh-TW": ["values-zh-rTW", "values-zh-rHK", "values-b+zh+Hant"]}


def load():
    text = SOURCE.read_text(encoding="utf-8")
    start = text.index("const STRINGS = ") + len("const STRINGS = ")
    end = text.index("\n};", start) + 2
    body = re.sub(r",(\s*[}\]])", r"\1", text[start:end])
    return json.loads(body)


def android_value(value):
    value = escape(value).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if value[:1] in ("@", "?"):
        value = "\\" + value
    return value


def main():
    strings = load()
    keys = list(strings["en"])
    for locale, folders in TARGETS.items():
        table = strings[locale]
        missing = [key for key in keys if key not in table]
        if missing:
            raise SystemExit(f"{locale} lacks {missing}")
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by android/tools/import_webui_strings.py from module/webroot/i18n.js. Do not edit. -->",
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,UnusedResources">']
        for key in keys:
            name = "w_" + re.sub(r"[^A-Za-z0-9_]", "_", key)
            lines.append(f'    <string name="{name}" formatted="false">{android_value(table[key])}</string>')
        lines.append("</resources>\n")
        for folder in folders:
            out = RES / folder / "strings_webui.xml"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Imported {len(keys)} strings for {', '.join(TARGETS)}")


if __name__ == "__main__":
    main()
